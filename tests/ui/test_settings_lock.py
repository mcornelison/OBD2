def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _view(fn: str, *args: object) -> Any:
    proc = subprocess.run(
        [_NODE, _PROBE, fn, *[json.dumps(a) for a in args]],
        capture_output=True, text=True, encoding="utf-8",
    )
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


def _fixture(name: str) -> dict[str, Any]:
    with open(os.path.join(_FIXTURE_DIR, f"{name}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _routes(fx: dict[str, Any], *, gear: dict | None = None) -> dict[str, Any]:
    payloads = fx["payloads"]
    routes: dict[str, Any] = {
        "/system-status": payloads["system-status"],
        "/gear": gear if gear is not None else payloads["gear"],
    }
    write = payloads.get("settings-write")
    if write is not None:
        routes["/settings"] = (
            write["body"] if write["status"] == 200
            else {"__status": write["status"], "__body": write["body"]}
        )
    return routes


def _carousel(tmp_path, settings: dict[str, Any], holdPostRounds: int = 0) -> str:
    """A temp copy of the SHIPPED carousel.js with the injections prepended."""
    prefix = [
        # location.reload after a confirmed reload-row save: counted, not run.
        "globalThis.location = {reload: function () {"
        " document.body.setAttribute('data-reloads', 'yes'); }};",
        f"window.DISPLAY_SETTINGS = {json.dumps(settings)};",
    ]
    if holdPostRounds:
        prefix.append(
            "(function () {\n"
            "  var realFetch = globalThis.fetch;\n"
            "  globalThis.fetch = function (url, options) {\n"
            "    if (url !== '/settings' || !options || options.method !== 'POST') {\n"
            "      return realFetch(url, options);\n"
            "    }\n"
            f"    var hops = {holdPostRounds};\n"
            "    return new Promise(function (resolve) {\n"
            "      function hop() {\n"
            "        hops -= 1;\n"
            "        if (hops > 0) { setTimeout(hop); return; }\n"
            "        var band = document.getElementById('settings-list');\n"
            "        document.body.setAttribute('data-locked-at-answer',\n"
            "          String(band && band.getAttribute('data-locked')));\n"
            "        resolve(realFetch(url, options));\n"
            "      }\n"
            "      setTimeout(hop);\n"
            "    });\n"
            "  };\n"
            "})();"
        )
    path = tmp_path / "carousel.js"
    path.write_text("\n".join(prefix) + "\n" + _read(_JS), encoding="utf-8")
    return str(path)


def _run(tmp_path, name: str, steps: list[dict], *, holdPostRounds: int = 0,
         settings: dict | None = None, gear: dict | None = None) -> dict[str, Any]:
    fx = _fixture(name)
    out = rh.runDashboard(
        routes=_routes(fx, gear=gear),
        steps=steps,
        carouselPath=_carousel(
            tmp_path, settings if settings is not None else fx["payloads"]["settings"],
            holdPostRounds,
        ),
        viewport=PANEL,
        nowMs=_NOW_MS,
    )
    out["surface"] = rh.dashboardSurface(out["tree"], viewport=PANEL)
    return out


def _text(node: dict) -> str:
    out = []
    for child in node.get("children", []):
        out.append(child["text"] if "text" in child else _text(child))
    return "".join(out)


def _attrs(path: list[dict]) -> dict[str, Any]:
    return path[-1].get("attrs", {})


def _band(surface) -> list[dict]:
    path = surface.pathById("settings-list")
    assert path is not None, "#settings-list is not in the DOM"
    return path


def _lockLine(surface) -> str | None:
    path = surface.pathById("settings-lock")
    assert path is not None, "#settings-lock is not in the DOM"
    if _attrs(path).get("hidden") is not None:
        return None
    return _text(path[-1])


def _rows(surface) -> dict[str, list[dict]]:
    return {_attrs(p)["data-key"]: p for p in surface.pathsByClass("set-row")}


def _rowText(surface, key: str, cls: str) -> str:
    row = _rows(surface)[key][-1]
    found: list[str] = []

    def walk(node: dict) -> None:
        if cls in (node.get("attrs", {}).get("class") or "").split():
            found.append(_text(node))
        for child in node.get("children", []):
            if "tag" in child:
                walk(child)

    walk(row)
    assert found, f"no .{cls} in the {key} row"
    return found[0]


def _posts(out: dict[str, Any]) -> list[dict]:
    return [f for f in out["fetches"] if f["url"] == "/settings" and f["method"] == "POST"]


def _menuOpen(surface) -> bool:
    return surface.rendered(surface.pathById("setup-menu"))


