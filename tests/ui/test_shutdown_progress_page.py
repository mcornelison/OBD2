@pytest.mark.parametrize("name", _NAMES)
def test_fixtureOnDisk_equalsWhatTheGeneratorBuilds(name):
    """
    Given: the generator (buildShutdownState + CeremonyProgress / ceremonySteps)
    Then:  each committed fixture is byte-equal to what it builds now
    """
    gen = _generator()
