def _code(js: str) -> str:
    body = re.sub(r"/\*.*?\*/", "", js, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", "", body)


def pageStepNames(js: str) -> set[str]:
    """The keys of the page's STEP_WORDS object literal, comments stripped."""
    match = re.search(r"\bSTEP_WORDS\s*=\s*\{([^{}]*)\}", _code(js))
    assert match, "shutdown-state-poll.js has no STEP_WORDS table"
    return set(re.findall(r"""["']([^"']+)["']\s*:""", match.group(1)))


def test_pageStepNames_areCeremonyOrderPlusTheHold():
    """
    Given: the shipped shutdown-state-poll.js
    Then:  its step-word keys are exactly CEREMONY_ORDER + STEP_MONTHLY_TEST_HOLD
    """
    with open(_POLL_JS, encoding="utf-8") as fh:
        names = pageStepNames(fh.read())

    assert names == set(CEREMONY_ORDER) | {STEP_MONTHLY_TEST_HOLD}


def test_stepNameGuard_seesAnAddedKey():
    js = 'var STEP_WORDS = { "shed": "a", /* "x": "y" */ "custody": "b", "extra": "c" };'
    assert pageStepNames(js) == {"shed", "custody", "extra"}


def test_pageStepWords_areTheSpecsVerbatim():
    with open(_POLL_JS, encoding="utf-8") as fh:
        match = re.search(r"\bSTEP_WORDS\s*=\s*\{([^{}]*)\}", _code(fh.read()))
    pairs = dict(re.findall(r"""["']([^"']+)["']\s*:\s*["']([^"']*)["']""", match.group(1)))

    assert pairs == {**_WORDS, "drain": _OTHER}


