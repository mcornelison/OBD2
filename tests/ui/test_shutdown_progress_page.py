def _generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("shutdown_fixture_generate", _GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fixture(name: str) -> dict[str, Any]:
    with open(os.path.join(_FIXTURES, f"{name}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _run(sequence: list[Any], tailRounds: int = 4) -> dict[str, Any]:
    rounds = len(sequence) * (_EMIT_MS // 250) + tailRounds
    return rh.runShutdownSplash(sequence, rounds=rounds, emitIntervalMs=_EMIT_MS)


def _pct(fill: str | None) -> float | None:
    if fill is None:
        return None
    match = re.fullmatch(r"\s*([0-9.]+)%\s*", fill)
    assert match, f"fill is not a percentage: {fill!r}"
    return float(match.group(1))


def _frames(result: dict[str, Any]) -> list[tuple[int | None, str | None, str | None]]:
    """The painted frames, rounded to whole percent: (fill, line1, line2)."""
    out = []
    for entry in result["progressLog"]:
        pct = _pct(entry["fill"])
        out.append((None if pct is None else round(pct), entry["line1"], entry["line2"]))
    return out


def _fills(result: dict[str, Any]) -> list[float]:
    return [p for p in (_pct(e["fill"]) for e in result["progressLog"]) if p is not None]


def _state(phase: str, step: dict | None, sync: Any = None) -> dict[str, Any]:
    return buildShutdownState(
        phase,
        tGraceStartedAtIso="2026-10-25T12:00:00Z",
        tGraceTotalS=7.0,
        tRemainingS=0.0,
        reason=DEFAULT_REASON,
        nowIso="2026-10-25T12:00:09Z",
        step=step,
        sync=sync,
    )


def _sync(state: str, outcome: str | None, waiting: Any, confirmed: Any) -> dict[str, Any]:
    return _generator().syncPayload(state, outcome, waiting, confirmed)


def _step(index: Any, of: Any, name: Any) -> dict[str, Any]:
    return {"index": index, "of": of, "name": name}


