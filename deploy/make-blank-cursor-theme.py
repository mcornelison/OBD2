"""Generate the eclipse-blank cursor theme.

CSS ``cursor: none`` hides the pointer only inside Chromium; labwc draws the
frames before Chromium first maps and during the splash -> dashboard hand-off
(Atlas MEASURED 2026-10-25). A theme whose every cursor is transparent hides it
there too, and pointer input cannot undo it (labwc's HideCursor action is
one-shot; REJECTED).

Stdlib only: this runs under the Pi's system python3, not the project venv.
Every write is temp + rename, and a file already holding the wanted bytes (or a
symlink already pointing at the image) is left alone, so a re-run is
byte-identical and reports ``already current``.

Exit status: 0 on success (a missing source theme is one WARN, not a failure);
1 when the theme cannot be written, naming the icons dir.
"""

from __future__ import annotations

import argparse
import os
import struct
import sys
from collections.abc import Callable
from pathlib import Path

THEME_NAME = "eclipse-blank"
DEFAULT_ICONS_DIR = "/usr/share/icons"
DEFAULT_SOURCE_THEME = "/usr/share/icons/Adwaita"

# The one image every cursor name points at. Not a cursor name itself.
IMAGE_NAME = "eclipse-blank-transparent"

# Present even when the source theme lacks them: 'left_ptr' is the X11 arrow,
# 'default' the CSS/cursor-spec name labwc and wlroots ask for.
ALWAYS_NAMES = ("default", "left_ptr")

# Nominal size and edge length: labwc's default XCURSOR_SIZE (labwc-config(5)).
# libXcursor picks the nearest nominal size, so one size serves every request.
CURSOR_SIZE = 24

# Xcursor(3) file format: little-endian CARD32 fields throughout.
XCURSOR_MAGIC = b"Xcur"
XCURSOR_FILE_HEADER_SIZE = 16
XCURSOR_FILE_VERSION = 0x00010000
XCURSOR_IMAGE_TYPE = 0xFFFD0002
XCURSOR_IMAGE_HEADER_SIZE = 36
XCURSOR_IMAGE_VERSION = 1
XCURSOR_TOC_ENTRY_SIZE = 12

INDEX_THEME = (
    "[Icon Theme]\n"
    f"Name={THEME_NAME}\n"
    "Comment=Eclipse kiosk: every cursor fully transparent (generated by "
    "deploy/make-blank-cursor-theme.py)\n"
)

TMP_SUFFIX = ".tmp-eclipse-blank"

Symlinker = Callable[[str, str], None]


class ThemeWriteError(Exception):
    """The theme could not be written under the icons dir."""


def buildBlankImage(size: int = CURSOR_SIZE) -> bytes:
    """
    Build one Xcursor file holding a single size x size image, every pixel 0.

    Args:
        size: Nominal size and edge length in pixels.

    Returns:
        The Xcursor file bytes: header, a one-entry table of contents, one image
        chunk whose ARGB pixels all have alpha 0.
    """
    ntoc = 1
    position = XCURSOR_FILE_HEADER_SIZE + XCURSOR_TOC_ENTRY_SIZE * ntoc
    header = struct.pack(
        "<4sIII", XCURSOR_MAGIC, XCURSOR_FILE_HEADER_SIZE, XCURSOR_FILE_VERSION, ntoc
    )
    toc = struct.pack("<III", XCURSOR_IMAGE_TYPE, size, position)
    imageHeader = struct.pack(
        "<IIIIIIIII",
        XCURSOR_IMAGE_HEADER_SIZE,
        XCURSOR_IMAGE_TYPE,
        size,
        XCURSOR_IMAGE_VERSION,
        size,  # width
        size,  # height
        0,  # xhot
        0,  # yhot
        0,  # delay (not animated)
    )
    pixels = bytes(4 * size * size)
    return header + toc + imageHeader + pixels


def listCursorNames(sourceCursorsDir: Path) -> tuple[list[str], bool]:
    """
    List the cursor names to provide: the source theme's, plus ALWAYS_NAMES.

    Args:
        sourceCursorsDir: The system default theme's cursors dir.

    Returns:
        (sorted names, whether the source dir was found).
    """
    names = set(ALWAYS_NAMES)
    found = sourceCursorsDir.is_dir()
    if found:
        names.update(entry.name for entry in sourceCursorsDir.iterdir())
    names.discard(IMAGE_NAME)
    return sorted(names), found


def _writeFileIfChanged(path: Path, data: bytes) -> bool:
    if path.is_file() and not path.is_symlink() and path.read_bytes() == data:
        return False
    tmp = path.with_name(path.name + TMP_SUFFIX)
    tmp.write_bytes(data)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)
    return True


def _linkIfChanged(path: Path, target: str, symlink: Symlinker) -> bool:
    if path.is_symlink() and os.readlink(path) == target:
        return False
    tmp = path.with_name(path.name + TMP_SUFFIX)
    if tmp.is_symlink() or tmp.exists():
        tmp.unlink()
    symlink(target, str(tmp))
    os.replace(tmp, path)
    return True


def generateTheme(
    iconsDir: Path, sourceTheme: Path, symlink: Symlinker = os.symlink
) -> tuple[Path, int, int, bool]:
    """
    Write <iconsDir>/eclipse-blank: index.theme, one image, one link per name.

    Args:
        iconsDir: Where icon themes live (/usr/share/icons on the Pi).
        sourceTheme: The system default theme whose cursor names are mirrored.
        symlink: os.symlink, or a stand-in where the filesystem cannot symlink.

    Returns:
        (theme dir, link count, entries changed, whether the source was found).

    Raises:
        ThemeWriteError: Anything under iconsDir could not be written.
    """
    themeDir = iconsDir / THEME_NAME
    cursorsDir = themeDir / "cursors"
    names, found = listCursorNames(sourceTheme / "cursors")
    try:
        cursorsDir.mkdir(parents=True, exist_ok=True)
        indexBytes = INDEX_THEME.encode("utf-8")
        changed = int(_writeFileIfChanged(themeDir / "index.theme", indexBytes))
        changed += int(_writeFileIfChanged(cursorsDir / IMAGE_NAME, buildBlankImage()))
        for name in names:
            changed += int(_linkIfChanged(cursorsDir / name, IMAGE_NAME, symlink))
    except OSError as exc:
        raise ThemeWriteError(
            f"cannot write the {THEME_NAME} cursor theme under {iconsDir}: {exc}"
        ) from exc
    return themeDir, len(names), changed, found


def main(argv: list[str] | None = None, symlink: Symlinker = os.symlink) -> int:
    """
    CLI entry point.

    Args:
        argv: Arguments (default sys.argv[1:]).
        symlink: Passed to generateTheme.

    Returns:
        0 on success, 1 when the theme cannot be written.
    """
    parser = argparse.ArgumentParser(description="Generate the eclipse-blank cursor theme.")
    parser.add_argument("--icons-dir", default=DEFAULT_ICONS_DIR)
    parser.add_argument("--source-theme", default=DEFAULT_SOURCE_THEME)
    args = parser.parse_args(argv)
    sourceTheme = Path(args.source_theme)
    try:
        themeDir, links, changed, found = generateTheme(Path(args.icons_dir), sourceTheme, symlink)
    except ThemeWriteError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    if not found:
        print(
            f"WARN: {sourceTheme / 'cursors'} not found -- {THEME_NAME} carries only "
            f"{' and '.join(ALWAYS_NAMES)}.",
            file=sys.stderr,
        )
    if changed:
        print(
            f"{themeDir}: 1 transparent image, {links} symlinks "
            f"(one per {sourceTheme.name} cursor name; {' and '.join(ALWAYS_NAMES)} always)."
        )
    else:
        print(f"{themeDir}: already current (1 transparent image, {links} symlinks).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
